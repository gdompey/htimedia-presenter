#!/usr/bin/env node
// Copies the bundled presentation fonts (open-licence, from Fontsource) into src/renderer/fonts/
// and writes fonts.css. Only Latin + Latin Extended subsets (which include Ghanaian letters such as
// ɛ and ɔ where the font has them) and regular/bold/extra-bold weights are kept, so the app stays small.
//   node scripts/build-fonts.js
const fs = require('fs');
const path = require('path');
const { FONTS } = require('../src/shared/core.js');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'renderer', 'fonts');
const FILES = path.join(OUT, 'files');
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(FILES, { recursive: true });

const WEIGHTS = [400, 700, 800, 900];
const css = [];
let bytes = 0;
const licences = new Set();

for (const f of FONTS.filter(x => x.pkg)) {
  const dir = path.join(ROOT, 'node_modules', '@fontsource', f.pkg);
  if (!fs.existsSync(dir)) throw new Error('Missing @fontsource/' + f.pkg + ' (npm install)');
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  licences.add(f.family + ': ' + pkg.license);
  let found = 0;
  for (const w of WEIGHTS) {
    const file = path.join(dir, w + '.css');
    if (!fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, 'utf8');
    for (const block of src.match(/@font-face\s*{[^}]*}/g) || []) {
      const m = /url\(\.\/files\/([^)]+?-(latin|latin-ext)-\d+-normal\.woff2)\)/.exec(block);
      if (!m) continue;
      fs.copyFileSync(path.join(dir, 'files', m[1]), path.join(FILES, m[1]));
      bytes += fs.statSync(path.join(FILES, m[1])).size;
      const range = (/unicode-range:\s*([^;]+);/.exec(block) || [])[1];
      css.push(`@font-face{font-family:'${f.family}';font-style:normal;font-display:block;font-weight:${w};src:url(files/${m[1]}) format('woff2');${range ? 'unicode-range:' + range + ';' : ''}}`);
      found++;
    }
  }
  if (!found) throw new Error('No font files found for ' + f.family);
}

fs.writeFileSync(path.join(OUT, 'fonts.css'), '/* Generated by scripts/build-fonts.js - open-licence fonts from Fontsource. */\n' + css.join('\n') + '\n');
fs.writeFileSync(path.join(OUT, 'LICENSES.txt'), 'Bundled fonts (SIL Open Font License 1.1 unless noted) - https://fontsource.org\n' + [...licences].join('\n') + '\n');
console.log('Bundled ' + FONTS.filter(x => x.pkg).length + ' font families, ' + css.length + ' faces, ' + (bytes / 1048576).toFixed(1) + ' MB');
